#!/usr/bin/env bash
# Creates labels, milestones and issues for Feliz Navisquad.
# Run once from inside your local clone of the repo:  bash scripts/create-issues.sh
# Needs: gh (GitHub CLI), logged in with `gh auth login`.
set -euo pipefail

gh auth status >/dev/null 2>&1 || { echo "gh is not logged in. Run: gh auth login" >&2; exit 1; }
REPO=$(gh repo view --json nameWithOwner -q .nameWithOwner) || { echo "Run this inside the repo clone." >&2; exit 1; }
echo "Repo: $REPO"

# Guard against running twice (would create duplicates).
EXISTING=$(gh issue list --repo "$REPO" --search 'in:title "Project skeleton and CLAUDE.md"' --state all --json number -q 'length')
if [ "$EXISTING" != "0" ]; then
  echo "The issues already exist. Aborting so nothing is duplicated." >&2; exit 1
fi

# ---------- Labels ----------
gh label create code    --repo "$REPO" --color 26364A --description "Implementation work" --force
gh label create content --repo "$REPO" --color C5BFE0 --description "Adding exercises, routines or illustrations made outside the repo" --force
gh label create launch  --repo "$REPO" --color C9B27C --description "Needed for going live" --force

# ---------- Milestones ----------
EXISTING_MS=$(gh api "repos/$REPO/milestones?state=all&per_page=100" -q '.[].title')
milestone() { # title, due date (YYYY-MM-DD), description
  if grep -qxF "$1" <<<"$EXISTING_MS"; then echo "Milestone exists: $1"; return; fi
  gh api "repos/$REPO/milestones" -f title="$1" -f due_on="$2T22:59:59Z" -f description="$3" >/dev/null
  echo "Milestone: $1"
}
M1="1 Foundation";        milestone "$M1" 2026-11-18 "Skeleton, tokens, core logic. Placeholder replaced by the real app with the pre-December countdown."
M2="2 Calendar";          milestone "$M2" 2026-11-22 "Sleigh scene, throw interaction, menu, day 24."
M3="3 Workout flow";      milestone "$M3" 2026-11-25 "Content model, mode choice, exercise cards, celebration."
M4="4 Content & launch";  milestone "$M4" 2026-11-30 "All content in, polish, link preview, launch check."

# ---------- Issues ----------
issue() { # title, milestone, label ; body from stdin
  local url; url=$(gh issue create --repo "$REPO" --title "$1" --milestone "$2" --label "$3" --body-file -)
  echo "  $url  $1"
}

PRD='Read `CLAUDE.md` first. Sources: `docs/decisions.md`, `docs/prototype.html`, `docs/tokens.json`.'

