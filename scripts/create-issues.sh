- Create the folders from "Target structure" and the app shell as \`app.html\` in the repo root (lang, viewport, theme-color #1C2733, \`<main id="screen">\`, \`<script type="module" src="js/main.js">\`). The placeholder stays as \`index.html\` so the live site doesn't show work in progress; the issue "Calendar scene" swaps them.
